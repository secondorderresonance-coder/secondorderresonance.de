function buildTaskArchive(baseTasks, targetPerLevel) {
    const variantModes = [
        {
            label: "Rechenweg",
            prompt: "Notiere die wichtigsten Rechenschritte oder Begründungsschritte.",
            answerNote: "Der vollständige Lösungsweg gehört zur Antwort.",
            explanationNote: "Achte darauf, Definition, eingesetzte Formel und Ergebnis klar voneinander zu trennen."
        },
        {
            label: "Begründung",
            prompt: "Begründe kurz, warum genau diese Methode passt.",
            answerNote: "Die Begründung ist Teil der erwarteten Antwort.",
            explanationNote: "Die Methode soll nicht nur angewendet, sondern fachlich eingeordnet werden."
        },
        {
            label: "Fehleranalyse",
            prompt: "Nenne außerdem einen typischen Fehler, den man hier vermeiden muss.",
            answerNote: "Ergänze einen kurzen Hinweis zum häufigsten Fehler.",
            explanationNote: "Prüfe besonders Vorzeichen, Einheiten, Definitionsbereiche und Voraussetzungen."
        },
        {
            label: "Transfer",
            prompt: "Formuliere am Ende, woran man eine ähnliche Aufgabe erkennt.",
            answerNote: "Ergänze ein Erkennungsmerkmal für verwandte Aufgaben.",
            explanationNote: "Der Transferhinweis macht sichtbar, welches Muster hinter der Aufgabe steht."
        },
        {
            label: "Schnellcheck",
            prompt: "Führe einen kurzen Plausibilitätscheck des Ergebnisses durch.",
            answerNote: "Ein kurzer Plausibilitätscheck gehört zur Antwort.",
            explanationNote: "Der Schnellcheck soll zeigen, ob Größenordnung, Vorzeichen oder Grenzfall sinnvoll sind."
        }
    ];

    const byLevel = {};
    baseTasks.forEach(task => {
        if (!byLevel[task.level]) byLevel[task.level] = [];
        byLevel[task.level].push(task);
    });

    const expanded = [];
    Object.keys(byLevel).sort((a, b) => Number(a) - Number(b)).forEach(level => {
        const levelBase = byLevel[level];
        if (!levelBase || levelBase.length === 0) return;

        for (let idx = 0; idx < targetPerLevel; idx += 1) {
            const seed = levelBase[idx % levelBase.length];
            const variant = Math.floor(idx / levelBase.length) + 1;
            const focus = variantModes[(variant - 1) % variantModes.length];
            const cycle = Math.floor((variant - 1) / variantModes.length) + 1;
            const serial = String(idx + 1).padStart(3, "0");

            expanded.push({
                ...seed,
                id: `T-${level}-${serial}`,
                title: `${seed.title} (Variante ${variant}: ${focus.label})`,
                question: `${seed.question} [Serie ${variant}: ${focus.prompt}]`,
                answer: `${seed.answer} Zusatzfokus: ${focus.answerNote}`,
                explanation: `${seed.explanation} Variantenfokus (${focus.label}, Durchlauf ${cycle}): ${focus.explanationNote} Diese Aufgabe ist Teil der skalierbaren Archivserie ${variant} für Level ${level} und behält den vollständigen Lösungsweg der kuratierten Seed-Aufgabe bei.`
            });
        }
    });

    return expanded;
}
